SCENARIO_MAP = {s["id"]: s for s in SCENARIOS}
DEFAULT_SCENARIO = "free"


def get_scenario(scenario_id: str | None) -> dict:
    """按 id 取场景，找不到就回退到自由聊天"""
    return SCENARIO_MAP.get(scenario_id or DEFAULT_SCENARIO, SCENARIO_MAP[DEFAULT_SCENARIO])


def list_scenarios() -> list[dict]:
    """给前端的场景列表（不含内部 prompt，省流量也避免暴露提示词）"""
    return [
        {"id": s["id"], "emoji": s["emoji"], "name": s["name"],
         "jp_name": s["jp_name"], "category": s.get("category")}
        for s in SCENARIOS
    ]
