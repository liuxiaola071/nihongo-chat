def get_translation_quiz(direction: str = "random", count: int = 10, difficulty: int = 1) -> list[dict]:
    """
    生成翻译练习题。

    direction: "j2c" | "c2j" | "random"
    difficulty: 1~5 难度筛选
    count: 返回多少题
    """
    import random

    filtered = [p for p in TRANSLATION_PAIRS if difficulty <= 0 or p.get("diff", 1) <= difficulty]

    if direction == "j2c":
        filtered = [p for p in filtered if "jp" in p]
    elif direction == "c2j":
        filtered = [p for p in filtered if "cn" in p]
    # random 不过滤

    random.shuffle(filtered)
    return filtered[:count]


